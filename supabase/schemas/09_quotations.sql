-- =====================================================
-- TABLE: quotations
-- Description: Official wholesale quotations generated for bulk enquiries
-- Target DB: Supabase (PostgreSQL)
-- =====================================================

CREATE TABLE IF NOT EXISTS public.quotations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_number TEXT NOT NULL UNIQUE,
    enquiry_id BIGINT NOT NULL REFERENCES public.bulk_enquiries(id) ON DELETE RESTRICT,
    customer_name TEXT NOT NULL,
    business_name TEXT NOT NULL,
    phone_number TEXT NOT NULL,
    email TEXT,
    subtotal NUMERIC(10, 2) NOT NULL,
    discount_percent NUMERIC(5, 2) DEFAULT 0.00,
    discount_amount NUMERIC(10, 2) DEFAULT 0.00,
    tax_percent NUMERIC(5, 2) DEFAULT 12.00,       -- 12% GST standard on fruit beverages
    tax_amount NUMERIC(10, 2) DEFAULT 0.00,
    delivery_charges NUMERIC(10, 2) DEFAULT 0.00,
    grand_total NUMERIC(10, 2) NOT NULL,
    validity_date TEXT NOT NULL,
    payment_terms TEXT NOT NULL,
    notes_conditions TEXT,
    status TEXT NOT NULL DEFAULT 'Draft',          -- 'Draft', 'Sent', 'Accepted', 'Declined', 'Converted'
    created_by TEXT NOT NULL DEFAULT 'Admin',
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_quotations_quotation_number ON public.quotations (quotation_number);
CREATE INDEX IF NOT EXISTS idx_quotations_enquiry_id ON public.quotations (enquiry_id);
CREATE INDEX IF NOT EXISTS idx_quotations_status ON public.quotations (status);
CREATE INDEX IF NOT EXISTS idx_quotations_created_at ON public.quotations (created_at DESC);

COMMENT ON TABLE public.quotations IS 'Wholesale price quotations for bulk buyers';
