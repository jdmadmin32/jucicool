-- =====================================================
-- TABLE: product_categories
-- Description: Beverage and confectionery categories
-- Target DB: Supabase (PostgreSQL)
-- =====================================================

CREATE TABLE IF NOT EXISTS public.product_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    description TEXT,
    image_url TEXT,
    display_order INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Index for fast lookup by category slug
CREATE INDEX IF NOT EXISTS idx_product_categories_slug ON public.product_categories (slug);
CREATE INDEX IF NOT EXISTS idx_product_categories_display_order ON public.product_categories (display_order ASC);

COMMENT ON TABLE public.product_categories IS 'Categories for Juci Cool products (e.g. Fruit Drinks, Mango Drinks, Candies)';
