-- =====================================================
-- TABLE: product_images
-- Description: Additional gallery images for products
-- Target DB: Supabase (PostgreSQL)
-- =====================================================

CREATE TABLE IF NOT EXISTS public.product_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    image_url TEXT NOT NULL,
    display_order INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_product_images_product_id ON public.product_images (product_id);
CREATE INDEX IF NOT EXISTS idx_product_images_display_order ON public.product_images (display_order ASC);

COMMENT ON TABLE public.product_images IS 'Extra gallery images for products in detail view';
