-- =====================================================
-- TABLE: bulk_enquiry_items
-- Description: Products requested in a bulk B2B enquiry
-- Target DB: Supabase (PostgreSQL)
-- =====================================================

CREATE TABLE IF NOT EXISTS public.bulk_enquiry_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enquiry_id BIGINT NOT NULL REFERENCES public.bulk_enquiries(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
    product_name TEXT NOT NULL,
    pack_size TEXT NOT NULL,
    requested_quantity INTEGER NOT NULL CHECK (requested_quantity > 0),
    unit_label TEXT DEFAULT 'Units' -- 'Units', 'Cartons'
);

CREATE INDEX IF NOT EXISTS idx_bulk_enquiry_items_enquiry_id ON public.bulk_enquiry_items (enquiry_id);
CREATE INDEX IF NOT EXISTS idx_bulk_enquiry_items_product_id ON public.bulk_enquiry_items (product_id);

COMMENT ON TABLE public.bulk_enquiry_items IS 'Line items requested in bulk enquiries';
