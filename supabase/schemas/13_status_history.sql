-- =====================================================
-- TABLE: status_history
-- Description: Audit trail of status transitions for orders & enquiries
-- Target DB: Supabase (PostgreSQL)
-- =====================================================

CREATE TABLE IF NOT EXISTS public.status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type TEXT NOT NULL, -- 'retail_order', 'bulk_enquiry', 'wholesale_order'
    entity_id BIGINT NOT NULL,
    previous_status TEXT,
    new_status TEXT NOT NULL,
    changed_by TEXT NOT NULL,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_status_history_entity ON public.status_history (entity_type, entity_id);
CREATE INDEX IF NOT EXISTS idx_status_history_created_at ON public.status_history (created_at DESC);

COMMENT ON TABLE public.status_history IS 'Lifecycle timeline and transition logs for orders and enquiries';
