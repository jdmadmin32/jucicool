-- =====================================================
-- TABLE: bulk_enquiries
-- Description: B2B "Get Best Price" commercial enquiries
-- Target DB: Supabase (PostgreSQL)
-- =====================================================

CREATE TABLE IF NOT EXISTS public.bulk_enquiries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enquiry_number TEXT NOT NULL UNIQUE,
    customer_name TEXT NOT NULL,
    phone_number TEXT NOT NULL,
    email TEXT,
    business_name TEXT NOT NULL,
    customer_type TEXT NOT NULL, -- 'Retailer', 'Dealer', 'Distributor', 'Supermarket', 'Other'
    city TEXT NOT NULL,
    state TEXT NOT NULL,
    preferred_contact_method TEXT NOT NULL DEFAULT 'Phone', -- 'Phone', 'WhatsApp', 'Email'
    gstin TEXT,
    delivery_location TEXT,
    additional_notes TEXT,
    status TEXT NOT NULL DEFAULT 'New', -- 'New', 'Contacted', 'Quotation Prepared', 'Quotation Sent', 'Negotiation', 'Accepted', 'Converted to Order', 'Declined', 'Closed'
    assigned_to TEXT,
    internal_notes TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_bulk_enquiries_enquiry_number ON public.bulk_enquiries (enquiry_number);
CREATE INDEX IF NOT EXISTS idx_bulk_enquiries_status ON public.bulk_enquiries (status);
CREATE INDEX IF NOT EXISTS idx_bulk_enquiries_phone ON public.bulk_enquiries (phone_number);
CREATE INDEX IF NOT EXISTS idx_bulk_enquiries_created_at ON public.bulk_enquiries (created_at DESC);

COMMENT ON TABLE public.bulk_enquiries IS 'Wholesale and bulk buyer enquiry tickets';
