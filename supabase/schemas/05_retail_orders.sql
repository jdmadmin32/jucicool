-- =====================================================
-- TABLE: retail_orders
-- Description: Direct-to-consumer and retail orders
-- Target DB: Supabase (PostgreSQL)
-- =====================================================

CREATE TABLE IF NOT EXISTS public.retail_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number TEXT NOT NULL UNIQUE,
    customer_name TEXT NOT NULL,
    customer_phone TEXT NOT NULL,
    customer_email TEXT,
    delivery_address TEXT NOT NULL,
    city TEXT NOT NULL,
    state TEXT NOT NULL,
    pincode TEXT NOT NULL,
    subtotal NUMERIC(10, 2) NOT NULL,
    delivery_fee NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    total_amount NUMERIC(10, 2) NOT NULL,
    payment_method TEXT NOT NULL DEFAULT 'COD',     -- 'COD', 'UPI', 'CARD'
    payment_status TEXT NOT NULL DEFAULT 'Pending', -- 'Pending', 'Paid', 'Failed'
    order_status TEXT NOT NULL DEFAULT 'New',       -- 'New', 'Confirmed', 'Processing', 'Packed', 'Shipped', 'Delivered', 'Cancelled'
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_retail_orders_order_number ON public.retail_orders (order_number);
CREATE INDEX IF NOT EXISTS idx_retail_orders_customer_phone ON public.retail_orders (customer_phone);
CREATE INDEX IF NOT EXISTS idx_retail_orders_order_status ON public.retail_orders (order_status);
CREATE INDEX IF NOT EXISTS idx_retail_orders_created_at ON public.retail_orders (created_at DESC);

COMMENT ON TABLE public.retail_orders IS 'Customer retail checkout orders';
