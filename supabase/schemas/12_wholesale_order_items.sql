-- =====================================================
-- TABLE: wholesale_order_items
-- Description: Individual line items inside wholesale orders
-- Target DB: Supabase (PostgreSQL)
-- =====================================================

CREATE TABLE IF NOT EXISTS public.wholesale_order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wholesale_order_id BIGINT NOT NULL REFERENCES public.wholesale_orders(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
    product_name TEXT NOT NULL,
    pack_size TEXT NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10, 2) NOT NULL,
    total_price NUMERIC(10, 2) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_wholesale_order_items_order_id ON public.wholesale_order_items (wholesale_order_id);
CREATE INDEX IF NOT EXISTS idx_wholesale_order_items_product_id ON public.wholesale_order_items (product_id);

COMMENT ON TABLE public.wholesale_order_items IS 'Line items inside wholesale orders';
