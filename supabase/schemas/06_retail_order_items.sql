-- =====================================================
-- TABLE: retail_order_items
-- Description: Individual line items for retail orders
-- Target DB: Supabase (PostgreSQL)
-- =====================================================

CREATE TABLE IF NOT EXISTS public.retail_order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES public.retail_orders(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
    product_name TEXT NOT NULL,
    pack_size TEXT NOT NULL,
    unit_price NUMERIC(10, 2) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    total_price NUMERIC(10, 2) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_retail_order_items_order_id ON public.retail_order_items (order_id);
CREATE INDEX IF NOT EXISTS idx_retail_order_items_product_id ON public.retail_order_items (product_id);

COMMENT ON TABLE public.retail_order_items IS 'Line items belonging to retail orders';
