-- =====================================================
-- TABLE: products
-- Description: Retail & wholesale beverages, juices, candies and jellies
-- Target DB: Supabase (PostgreSQL)
-- =====================================================

CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    flavor TEXT NOT NULL,
    category_id BIGINT NOT NULL REFERENCES public.product_categories(id) ON DELETE RESTRICT,
    pack_size TEXT NOT NULL,
    packaging_type TEXT NOT NULL,
    description TEXT,
    retail_price NUMERIC(10, 2) NOT NULL,
    wholesale_price NUMERIC(10, 2) DEFAULT 0.00,
    stock_quantity INTEGER NOT NULL DEFAULT 100,
    min_wholesale_qty INTEGER NOT NULL DEFAULT 50,
    image_url TEXT NOT NULL,
    shot_image_url TEXT,
    is_active INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    featured INTEGER NOT NULL DEFAULT 0 CHECK (featured IN (0, 1)),
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Indexes for performance & catalog querying
CREATE INDEX IF NOT EXISTS idx_products_category_id ON public.products (category_id);
CREATE INDEX IF NOT EXISTS idx_products_is_active ON public.products (is_active);
CREATE INDEX IF NOT EXISTS idx_products_featured ON public.products (featured);
CREATE INDEX IF NOT EXISTS idx_products_name_flavor ON public.products (name, flavor);

COMMENT ON TABLE public.products IS 'Juci Cool product catalog with retail & wholesale pricing';
