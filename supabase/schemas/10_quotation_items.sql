-- =====================================================
-- TABLE: quotation_items
-- Description: Line items and negotiated unit prices in a quotation
-- Target DB: Supabase (PostgreSQL)
-- =====================================================

CREATE TABLE IF NOT EXISTS public.quotation_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_id BIGINT NOT NULL REFERENCES public.quotations(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
    product_name TEXT NOT NULL,
    pack_size TEXT NOT NULL,
    requested_quantity INTEGER NOT NULL CHECK (requested_quantity > 0),
    approved_unit_price NUMERIC(10, 2) NOT NULL, -- Private wholesale price set by admin
    total_price NUMERIC(10, 2) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_quotation_items_quotation_id ON public.quotation_items (quotation_id);
CREATE INDEX IF NOT EXISTS idx_quotation_items_product_id ON public.quotation_items (product_id);

COMMENT ON TABLE public.quotation_items IS 'Line items inside wholesale quotations';
