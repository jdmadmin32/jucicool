-- =====================================================
-- TABLE: wholesale_orders
-- Description: Confirmed B2B wholesale orders converted from accepted quotations
-- Target DB: Supabase (PostgreSQL)
-- =====================================================

CREATE TABLE IF NOT EXISTS public.wholesale_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number TEXT NOT NULL UNIQUE,
    quotation_id BIGINT REFERENCES public.quotations(id) ON DELETE SET NULL,
    enquiry_id BIGINT REFERENCES public.bulk_enquiries(id) ON DELETE SET NULL,
    business_name TEXT NOT NULL,
    contact_person TEXT NOT NULL,
    phone_number TEXT NOT NULL,
    email TEXT,
    delivery_address TEXT,
    city TEXT,
    state TEXT,
    agreed_total NUMERIC(10, 2) NOT NULL,
    advance_paid NUMERIC(10, 2) DEFAULT 0.00,
    payment_status TEXT NOT NULL DEFAULT 'Pending',         -- 'Pending', 'Partial Advance', 'Paid', 'Credit'
    fulfillment_status TEXT NOT NULL DEFAULT 'Order Placed', -- 'Order Placed', 'Processing', 'Packed', 'Dispatched', 'Delivered', 'Cancelled'
    order_date TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    expected_delivery_date TEXT,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_wholesale_orders_order_number ON public.wholesale_orders (order_number);
CREATE INDEX IF NOT EXISTS idx_wholesale_orders_quotation_id ON public.wholesale_orders (quotation_id);
CREATE INDEX IF NOT EXISTS idx_wholesale_orders_enquiry_id ON public.wholesale_orders (enquiry_id);
CREATE INDEX IF NOT EXISTS idx_wholesale_orders_phone ON public.wholesale_orders (phone_number);
CREATE INDEX IF NOT EXISTS idx_wholesale_orders_fulfillment ON public.wholesale_orders (fulfillment_status);
CREATE INDEX IF NOT EXISTS idx_wholesale_orders_created_at ON public.wholesale_orders (created_at DESC);

COMMENT ON TABLE public.wholesale_orders IS 'Confirmed B2B wholesale orders converted from quotations';
