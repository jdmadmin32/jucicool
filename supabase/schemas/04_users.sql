-- =====================================================
-- TABLE: users
-- Description: Admin accounts, sales reps, and registered retail/dealer customers
-- Target DB: Supabase (PostgreSQL)
-- =====================================================

CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    full_name TEXT NOT NULL,
    phone TEXT,
    role TEXT NOT NULL DEFAULT 'customer' CHECK (role IN ('admin', 'sales_rep', 'customer')),
    business_name TEXT,
    customer_type TEXT DEFAULT 'Individual',
    city TEXT,
    state TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_users_email ON public.users (email);
CREATE INDEX IF NOT EXISTS idx_users_role ON public.users (role);
CREATE INDEX IF NOT EXISTS idx_users_phone ON public.users (phone);

COMMENT ON TABLE public.users IS 'Application users including admins, dealers, and retail customers';
